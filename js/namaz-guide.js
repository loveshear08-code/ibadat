/* =========================================================
   GET LANGUAGE FROM IBADAT SETTINGS
   ========================================================= */

function getNamazLanguage() {

    try {

        const saved = localStorage.getItem("ibadatSettings");

        if (!saved) {
            return "bn";
        }

        const settings = JSON.parse(saved);

        if (
            settings &&
            (
                settings.lang === "bn" ||
                settings.lang === "en" ||
                settings.lang === "hi"
            )
        ) {
            return settings.lang;
        }

    } catch (error) {
        console.log("Namaz language read error:", error);
    }

    return "bn";
}


