/* =========================================================
   LANGUAGE
   ========================================================= */

function getLanguage(){

    try{

        const saved =
            JSON.parse(
                localStorage.getItem("ibadatSettings")
            );

        if(
            saved &&
            ["bn","en","hi"].includes(saved.lang)
        ){
            return saved.lang;
        }

    }catch(error){

        console.log(error);

    }

    return "bn";
}


/* =========================================================
   APPLY LANGUAGE
   ========================================================= */

function applyLanguage(){

    const lang = getLanguage();
    const t = TEXT[lang];

    document.documentElement.lang = lang;

    document.title =
        lang === "bn"
            ? "IBADAT - নামাজ"
            : lang === "hi"
                ? "IBADAT - नमाज़"
                : "IBADAT - Namaz";


    setText("pageTitle", t.pageTitle);

    setText("introTitle", t.introTitle);

    setText("introText", t.introText);

    setText("titlePurity", t.purityTitle);
    setText("descPurity", t.purityDesc);

    setText("titleLearn", t.learnTitle);
    setText("descLearn", t.learnDesc);

    setText("titleRecitations", t.recitationsTitle);
    setText("descRecitations", t.recitationsDesc);

    setText("titleJamaat", t.jamaatTitle);
    setText("descJamaat", t.jamaatDesc);


    /*
     * যদি কোনো section বর্তমানে খোলা থাকে,
     * language পরিবর্তন হলে সেটিও সঙ্গে সঙ্গে
     * নতুন ভাষায় update হবে।
     */

    const currentSection =
        document.getElementById("sectionPage").dataset.section;

    if(currentSection){

        showSection(
            currentSection,
            false
        );

    }

}


function setText(id, text){

    const element =
        document.getElementById(id);

    if(element){

        element.textContent = text;

    }

}


/* =========================================================
   SHOW SECTION
   ========================================================= */

function showSection(sectionName, updateHistory = true){

    const lang = getLanguage();

    const section =
        TEXT[lang].sections[sectionName];

    if(!section){
        return;
    }


    const mainMenu =
        document.getElementById("mainMenu");

    const sectionPage =
        document.getElementById("sectionPage");

    const sectionTitle =
        document.getElementById("sectionTitle");

    const sectionContent =
        document.getElementById("sectionContent");


    mainMenu.classList.add("hidden");

    sectionPage.classList.remove("hidden");

    sectionPage.dataset.section =
        sectionName;


    sectionTitle.textContent =
        section.title;


    sectionContent.innerHTML = "";


    section.items.forEach(
        function(item){

            const card =
                document.createElement("div");

            card.className =
                "content-card";


            const title =
                document.createElement("div");

            title.className =
                "content-title";

            title.textContent =
                item[0];


            const text =
                document.createElement("div");

            text.className =
                "content-text";

            text.textContent =
                item[1];


            card.appendChild(title);

            card.appendChild(text);

            sectionContent.appendChild(card);

        }
    );


    if(updateHistory){

        history.pushState(
            {
                section: sectionName
            },
            "",
            "#"+sectionName
        );

    }

}


/* =========================================================
   CLOSE SECTION
   ========================================================= */

function closeSection(){

    const mainMenu =
        document.getElementById("mainMenu");

    const sectionPage =
        document.getElementById("sectionPage");


    sectionPage.classList.add("hidden");

    sectionPage.dataset.section = "";

    mainMenu.classList.remove("hidden");

}


/* =========================================================
   NAVIGATION
   ========================================================= */

function setupNavigation(){

    const cards =
        document.querySelectorAll(".guide-card");


    cards.forEach(
        function(card){

            card.addEventListener(
                "click",
                function(){

                    showSection(
                        card.dataset.section
                    );

                }
            );

        }
    );


    document
        .getElementById("sectionBackButton")
        .addEventListener(
            "click",
            function(){

                history.back();

            }
        );


    window.addEventListener(
        "popstate",
        function(){

            closeSection();

        }
    );

}


/* =========================================================
   HOME BACK BUTTON
   ========================================================= */

function setupHomeBack(){

    document
        .getElementById("backButton")
        .addEventListener(
            "click",
            function(){

                window.location.href =
                    "../index.html";

            }
        );

}


/* =========================================================
   LANGUAGE SYNC
   ========================================================= */

let lastLanguage = null;


function syncLanguage(){

    const currentLanguage =
        getLanguage();


    if(
        currentLanguage !== lastLanguage
    ){

        lastLanguage =
            currentLanguage;

        applyLanguage();

    }

}


/* =========================================================
   START
   ========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    function(){

        lastLanguage =
            getLanguage();

        applyLanguage();

        setupNavigation();

        setupHomeBack();


        /*
         * Settings page থেকে language বদলালে
         * এই page-ও automatic update হবে।
         */

        setInterval(
            syncLanguage,
            500
        );


        /*
         * সরাসরি #purity ইত্যাদি URL খুললেও
         * সেই section দেখাবে।
         */

        const hash =
            window.location.hash.replace("#","");


        if(
            TEXT[getLanguage()].sections[hash]
        ){

            showSection(
                hash,
                false
            );

        }

    }
);
