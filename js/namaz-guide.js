/* ================= GET LANGUAGE ================= */

function getNamazLanguage(){

    try{

        const raw =
            localStorage.getItem("appSettings");

        if(!raw) return "bn";

        const settings =
            JSON.parse(raw);

        if(
            settings.lang === "bn" ||
            settings.lang === "en" ||
            settings.lang === "hi"
        ){

            return settings.lang;

        }

    }catch(e){}

    return "bn";
}


/* ================= APPLY LANGUAGE ================= */

function applyNamazLanguage(){

    const lang =
        getNamazLanguage();

    const t =
        NAMAZ_GUIDE_TEXT[lang] ||
        NAMAZ_GUIDE_TEXT.bn;


    document.documentElement.lang =
        lang;


    document.title =
        t.title;


    document.getElementById(
        "pageTitle"
    ).innerText =
        t.title;


    document.getElementById(
        "introTitle"
    ).innerText =
        t.introTitle;


    document.getElementById(
        "introText"
    ).innerText =
        t.introText;


    const ids = [

        "wudu",
        "what",
        "preparation",
        "times",
        "rakat",
        "learn",
        "duas",
        "jamaat",
        "mistakes",
        "special",
        "women",
        "quick"

    ];


    ids.forEach(id => {

        const title =
            document.getElementById(
                "title" +
                id.charAt(0).toUpperCase() +
                id.slice(1)
            );

        const desc =
            document.getElementById(
                "desc" +
                id.charAt(0).toUpperCase() +
                id.slice(1)
            );


        if(title){

            title.innerText =
                t.cards[id].title;

        }


        if(desc){

            desc.innerText =
                t.cards[id].desc;

        }

    });

}


/* ================= NAVIGATION ================= */

function setupNamazNavigation(){

    const cards =
        document.querySelectorAll(
            ".guide-card"
        );


    cards.forEach(card => {

        card.addEventListener(
            "click",
            function(){

                const page =
                    this.dataset.page;


                /*
                 * এই পেজগুলো আমরা
                 * পরের ধাপে তৈরি করব।
                 */

                const pages = {

                    wudu:
                        "namaz-wudu.html",

                    what:
                        "namaz-what.html",

                    preparation:
                        "namaz-preparation.html",

                    times:
                        "namaz-times.html",

                    rakat:
                        "namaz-rakat.html",

                    learn:
                        "namaz-learn.html",

                    duas:
                        "namaz-duas.html",

                    jamaat:
                        "namaz-jamaat.html",

                    mistakes:
                        "namaz-mistakes.html",

                    special:
                        "namaz-special.html",

                    women:
                        "namaz-women.html",

                    quick:
                        "namaz-quick.html"

                };


                if(pages[page]){

                    window.location.href =
                        pages[page];

                }

            }
        );

    });

}


/* ================= BACK ================= */

function setupBackButton(){

    const back =
        document.getElementById(
            "backBtn"
        );


    if(back){

        back.addEventListener(
            "click",
            function(){

                window.location.href =
                    "../index.html";

            }
        );

    }

}


/* ================= LANGUAGE SYNC ================= */

let lastNamazLanguage =
    null;


function syncNamazLanguage(){

    const current =
        getNamazLanguage();


    if(
        current !==
        lastNamazLanguage
    ){

        lastNamazLanguage =
            current;

        applyNamazLanguage();

    }

}


/* ================= INIT ================= */

document.addEventListener(
    "DOMContentLoaded",
    function(){

        lastNamazLanguage =
            getNamazLanguage();

        applyNamazLanguage();

        setupNamazNavigation();

        setupBackButton();


        setInterval(
            syncNamazLanguage,
            1000
        );

    }
);
