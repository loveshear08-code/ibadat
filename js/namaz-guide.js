/* =====================================================
LANGUAGE HELPER
===================================================== */

function getLanguage(){

try{

    /*
       Support both possible settings keys.
    */

    let saved =
        localStorage.getItem("ibadatSettings");


    if(!saved){

        saved =
            localStorage.getItem("appSettings");
    }


    if(saved){

        const settings =
            JSON.parse(saved);


        if(
            settings.lang === "bn" ||
            settings.lang === "en" ||
            settings.lang === "hi"
        ){

            return settings.lang;
        }
    }

}catch(e){}


return "bn";

}

/* =====================================================
NUMBER LOCALIZATION
===================================================== */

function localizeNumbers(
value,
lang
){

if(lang === "bn"){

    return String(value)

        .replace(
            /0/g,"০"
        )

        .replace(
            /1/g,"১"
        )

        .replace(
            /2/g,"২"
        )

        .replace(
            /3/g,"৩"
        )

        .replace(
            /4/g,"৪"
        )

        .replace(
            /5/g,"৫"
        )

        .replace(
            /6/g,"৬"
        )

        .replace(
            /7/g,"৭"
        )

        .replace(
            /8/g,"৮"
        )

        .replace(
            /9/g,"৯"
        );

}


if(lang === "hi"){

    return String(value)

        .replace(
            /0/g,"०"
        )

        .replace(
            /1/g,"१"
        )

        .replace(
            /2/g,"२"
        )

        .replace(
            /3/g,"३"
        )

        .replace(
            /4/g,"४"
        )

        .replace(
            /5/g,"५"
        )

        .replace(
            /6/g,"६"
        )

        .replace(
            /7/g,"७"
        )

        .replace(
            /8/g,"८"
        )

        .replace(
            /9/g,"९"
        );

}


return String(value);

}

/* =====================================================
SET TEXT
===================================================== */

function setText(
id,
value
){

const element =
    document.getElementById(id);


if(element){

    element.textContent =
        value;
}

}

