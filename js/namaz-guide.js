/* =========================================================
   LANGUAGE
   ========================================================= */

function getLanguage(){

    try{

        const saved =
            JSON.parse(
                localStorage.getItem("ibadatSettings")
            );

        if(
            saved &&
            ["bn","en","hi"].includes(saved.lang)
        ){

            return saved.lang;

        }

    }catch(error){

        console.log(error);

    }

    return "bn";
}


/* =========================================================
   SET TEXT
   ========================================================= */

function setText(id, text){

    const element =
        document.getElementById(id);

    if(element){

        element.textContent = text;

    }

}


/* =========================================================
   APPLY LANGUAGE
   ========================================================= */

function applyLanguage(){

    const lang = getLanguage();

    const t = TEXT[lang];


    document.documentElement.lang = lang;


    document.title =
        lang === "bn"
            ? "IBADAT - নামাজ"
            : lang === "hi"
                ? "IBADAT - नमाज़"
                : "IBADAT - Namaz";


    /* Main page */

    setText(
        "pageTitle",
        t.pageTitle
    );


    setText(
        "infoTitle",
        t.infoTitle
    );


    setText(
        "infoText1",
        t.infoText1
    );


    setText(
        "infoText2",
        t.infoText2
    );


    setText(
        "infoMore",
        t.infoMore
    );


    /* Four main options */

    setText(
        "titlePurity",
        t.purityTitle
    );

    setText(
        "descPurity",
        t.purityDesc
    );


    setText(
        "titleLearn",
        t.learnTitle
    );

    setText(
        "descLearn",
        t.learnDesc
    );


    setText(
        "titleRecitations",
        t.recitationsTitle
    );

    setText(
        "descRecitations",
        t.recitationsDesc
    );


    setText(
        "titleJamaat",
        t.jamaatTitle
    );

    setText(
        "descJamaat",
        t.jamaatDesc
    );


    /* Second page */

    setText(
        "namazDetailsTitle",
        t.detailsTitle
    );


    setText(
        "dailyScheduleTitle",
        t.dailyScheduleTitle
    );


    setText(
        "dailyScheduleDesc",
        t.dailyScheduleDesc
    );


    setText(
        "specialScheduleTitle",
        t.specialScheduleTitle
    );


    setText(
        "specialScheduleDesc",
        t.specialScheduleDesc
    );


    /* Current schedule page */

    const schedulePage =
        document.getElementById(
            "schedulePage"
        );


    if(
        schedulePage &&
        !schedulePage.classList.contains("hidden")
    ){

        const type =
            schedulePage.dataset.schedule;


        if(type){

            showSchedule(
                type,
                false
            );

        }

    }


    /* Current blank section page */

    const sectionPage =
        document.getElementById(
            "sectionPage"
        );


    if(
        sectionPage &&
        !sectionPage.classList.contains("hidden")
    ){

        const sectionName =
            sectionPage.dataset.section;


        if(sectionName){

            showBlankSection(
                sectionName,
                false
            );

        }

    }

}


/* =========================================================
   SHOW NAMAZ DETAILS PAGE
   ========================================================= */

function showNamazDetails(
    updateHistory = true
){

    document
        .getElementById("mainMenu")
        .classList.add("hidden");


    document
        .getElementById("schedulePage")
        .classList.add("hidden");


    document
        .getElementById("sectionPage")
        .classList.add("hidden");


    document
        .getElementById("namazDetails")
        .classList.remove("hidden");


    if(updateHistory){

        history.pushState(
            {
                page: "namazDetails"
            },
            "",
            "#namaz-details"
        );

    }

}


/* =========================================================
   SHOW SCHEDULE
   daily / special
   ========================================================= */

function showSchedule(
    scheduleType,
    updateHistory = true
){

    const lang = getLanguage();

    const t = TEXT[lang];


    document
        .getElementById("mainMenu")
        .classList.add("hidden");


    document
        .getElementById("namazDetails")
        .classList.add("hidden");


    document
        .getElementById("sectionPage")
        .classList.add("hidden");


    document
        .getElementById("schedulePage")
        .classList.remove("hidden");


    document
        .getElementById("schedulePage")
        .dataset.schedule =
        scheduleType;


    const content =
        document.getElementById(
            "scheduleContent"
        );


    content.innerHTML = "";


    /* =====================================
       DAILY NAMAZ
       ===================================== */

    if(scheduleType === "daily"){

        setText(
            "schedulePageTitle",
            t.dailyScheduleTitle
        );


        const detailsCard =
            document.createElement("div");

        detailsCard.className =
            "details-card";


        const heading =
            document.createElement("div");

        heading.className =
            "details-heading";

        heading.textContent =
            t.fivePrayersTitle;


        detailsCard.appendChild(
            heading
        );


        t.prayers.forEach(
            function(prayer){

                const row =
                    document.createElement(
                        "div"
                    );

                row.className =
                    "prayer-row";


                const name =
                    document.createElement(
                        "span"
                    );

                name.className =
                    "prayer-name";

                name.textContent =
                    prayer[0] + ":";


                const count =
                    document.createElement(
                        "span"
                    );

                count.className =
                    "prayer-count";

                count.textContent =
                    prayer[1];


                row.appendChild(name);

                row.appendChild(count);


                detailsCard.appendChild(
                    row
                );

            }
        );


        content.appendChild(
            detailsCard
        );

    }


    /* =====================================
       SPECIAL NAMAZ
       ===================================== */

    else if(
        scheduleType === "special"
    ){

        setText(
            "schedulePageTitle",
            t.specialScheduleTitle
        );


        const placeholder =
            document.createElement(
                "div"
            );

        placeholder.className =
            "special-placeholder";

        placeholder.textContent =
            t.specialPlaceholder;


        content.appendChild(
            placeholder
        );

    }


    if(updateHistory){

        history.pushState(
            {
                page: "schedule",
                schedule: scheduleType
            },
            "",
            "#schedule-" + scheduleType
        );

    }

}


/* =========================================================
   SHOW BLANK PAGE FOR FOUR MAIN OPTIONS
   ========================================================= */

function showBlankSection(
    sectionName,
    updateHistory = true
){

    const lang = getLanguage();

    const t = TEXT[lang];


    let title = "";


    if(sectionName === "purity"){

        title = t.purityTitle;

    }

    else if(sectionName === "learn"){

        title = t.learnTitle;

    }

    else if(
        sectionName === "recitations"
    ){

        title =
            t.recitationsTitle;

    }

    else if(sectionName === "jamaat"){

        title =
            t.jamaatTitle;

    }


    document
        .getElementById("mainMenu")
        .classList.add("hidden");


    document
        .getElementById("namazDetails")
        .classList.add("hidden");


    document
        .getElementById("schedulePage")
        .classList.add("hidden");


    document
        .getElementById("sectionPage")
        .classList.remove("hidden");


    document
        .getElementById("sectionPage")
        .dataset.section =
        sectionName;


    setText(
        "sectionTitle",
        title
    );


    /*
     * এখন এই পেজ blank।
     * পরে আলাদা content/file যোগ করা হবে।
     */

    document
        .getElementById("sectionContent")
        .innerHTML = "";


    if(updateHistory){

        history.pushState(
            {
                page: "section",
                section: sectionName
            },
            "",
            "#" + sectionName
        );

    }

}


/* =========================================================
   RETURN TO MAIN PAGE
   ========================================================= */

function showMainMenu(){

    document
        .getElementById("namazDetails")
        .classList.add("hidden");


    document
        .getElementById("schedulePage")
        .classList.add("hidden");


    document
        .getElementById("sectionPage")
        .classList.add("hidden");


    document
        .getElementById("mainMenu")
        .classList.remove("hidden");


    document
        .getElementById("sectionPage")
        .dataset.section = "";

}


/* =========================================================
   NAVIGATION
   ========================================================= */

function setupNavigation(){


    /* =====================================
       TOP BACK BUTTON
       ===================================== */

    document
        .getElementById("backButton")
        .addEventListener(
            "click",
            function(){

                history.back();

            }
        );


    /* =====================================
       NAMAZ WHAT & WHY

       পুরো বোর্ড clickable
       ===================================== */

    document
        .getElementById("namazInfoCard")
        .addEventListener(
            "click",
            function(){

                showNamazDetails();

            }
        );


    /* =====================================
       DAILY SCHEDULE BOARD
       ===================================== */

    document
        .getElementById("dailyScheduleCard")
        .addEventListener(
            "click",
            function(){

                showSchedule("daily");

            }
        );


    /* =====================================
       SPECIAL SCHEDULE BOARD
       ===================================== */

    document
        .getElementById("specialScheduleCard")
        .addEventListener(
            "click",
            function(){

                showSchedule("special");

            }
        );


    /* =====================================
       FOUR MAIN OPTIONS

       এখন blank page খুলবে
       ===================================== */

    const cards =
        document.querySelectorAll(
            ".guide-card"
        );


    cards.forEach(
        function(card){

            card.addEventListener(
                "click",
                function(){

                    showBlankSection(
                        card.dataset.section
                    );

                }
            );

        }
    );


    /* =====================================
       NAMAZ DETAILS BACK
       ===================================== */

    document
        .getElementById(
            "namazDetailsBack"
        )
        .addEventListener(
            "click",
            function(){

                history.back();

            }
        );


    /* =====================================
       SCHEDULE BACK
       ===================================== */

    document
        .getElementById(
            "scheduleBackButton"
        )
        .addEventListener(
            "click",
            function(){

                history.back();

            }
        );


    /* =====================================
       FOUR OPTION BLANK PAGE BACK
       ===================================== */

    document
        .getElementById(
            "sectionBackButton"
        )
        .addEventListener(
            "click",
            function(){

                history.back();

            }
        );

}


/* =========================================================
   BROWSER BACK / FORWARD
   ========================================================= */

window.addEventListener(
    "popstate",
    function(){

        showMainMenu();

    }
);


/* =========================================================
   LANGUAGE CHANGE WATCHER
   ========================================================= */

window.addEventListener(
    "storage",
    function(event){

        if(
            event.key === "ibadatSettings"
        ){

            applyLanguage();

        }

    }
);


/* =========================================================
   INIT
   ========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    function(){

        applyLanguage();

        setupNavigation();

    }
);
